#!/usr/bin/env node
// Update the offline copy list in sw.js.
//
//   node tools/build-offline.mjs
//
// Lists every file the site needs to work without the internet, and sets VERSION to a fingerprint
// of their contents, so visitors' devices save a fresh copy whenever any of them changes.
// tools/build-data.mjs runs this after every data build. Run it yourself after editing other files
// (the tests remind you if you forget).

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SW = path.join(ROOT, 'sw.js');
const GENERATED = /\/\/ BEGIN GENERATED[\s\S]*?\/\/ END GENERATED/;
const list = (dir, ext) => fs.readdirSync(path.join(ROOT, dir)).filter(f => f.endsWith(ext)).sort().map(f => `${dir}/${f}`);

/** The files saved for offline use, as URLs relative to the site root ('./' is the page itself). */
export function offlineFiles() {
  return [
    './',
    'directory.html',
    '404.html',
    'site.webmanifest',
    'assets/css/app.css',
    ...list('assets/js', '.js'),
    ...list('assets/fonts', '.woff2'),
    'assets/img/favicon.svg',
    'assets/img/apple-touch-icon.png',
    'assets/img/icon-192.png',
    'data/businesses.json',
  ];
}

const fileOf = url => path.join(ROOT, url === './' ? 'index.html' : url);

// The fingerprint covers every saved file and the service worker's own code (everything outside its
// GENERATED block), so a change to either gives the saved copy a new name and never touches the one in use.
export function offlineVersion(files = offlineFiles()) {
  const h = crypto.createHash('sha256');
  for (const f of files) h.update(f).update('\0').update(fs.readFileSync(fileOf(f))).update('\0');
  h.update(fs.readFileSync(SW, 'utf8').replace(GENERATED, ''));
  return h.digest('hex').slice(0, 12);
}

export function buildOffline() {
  const files = offlineFiles();
  const missing = files.filter(f => !fs.existsSync(fileOf(f)));
  if (missing.length) throw new Error(`offline list names missing files: ${missing.join(', ')}`);
  const version = offlineVersion(files);
  const block = `// BEGIN GENERATED by tools/build-offline.mjs (don't edit by hand)\nconst VERSION = '${version}';\nconst CORE = ${JSON.stringify(files, null, 2).replace(/"/g, "'")};\n// END GENERATED`;
  const src = fs.readFileSync(SW, 'utf8');
  if (!GENERATED.test(src)) throw new Error('sw.js is missing its GENERATED block');
  fs.writeFileSync(SW, src.replace(GENERATED, block));
  const bytes = files.reduce((n, f) => n + fs.statSync(fileOf(f)).size, 0);
  console.log(`offline copy: ${files.length} files, ${(bytes / 1024 / 1024).toFixed(2)} MB, version ${version}`);
  // The install sheet in index.html promises "under 2 MB".
  if (bytes > 1.9 * 1024 * 1024) console.warn('warning: the offline copy is close to 2 MB; update "under 2 MB" in index.html (Save to my phone).');
  return { version, files, bytes };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildOffline();
